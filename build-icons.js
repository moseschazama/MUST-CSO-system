/**
 * Generates resources/icons.php from the Lucide SVG set installed by
 * `npm i -D lucide-static`. Run after adding a new icon name below:
 *
 *     node build-icons.js
 */
import fs from 'node:fs';

const names = [
    'arrow-right', 'arrow-up-right', 'book-open', 'calendar-days', 'calendar-plus',
    'camera', 'check', 'chevron-down', 'chevron-right', 'church', 'clipboard-list',
    'clock', 'copy', 'cross', 'download', 'external-link', 'facebook', 'file-text',
    'flame', 'flower-2', 'folder', 'folder-open', 'graduation-cap', 'hand-heart',
    'heart', 'heart-handshake', 'home', 'images', 'instagram', 'mail', 'map-pin',
    'menu', 'message-circle', 'music', 'music-2', 'phone', 'play', 'quote',
    'shield-check', 'sparkles', 'star', 'sunrise', 'users', 'video', 'x', 'youtube',
];

const out = {};
const missing = [];

for (const name of names) {
    const path = `node_modules/lucide-static/icons/${name}.svg`;
    if (!fs.existsSync(path)) {
        missing.push(name);
        continue;
    }
    const svg = fs.readFileSync(path, 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').trim();
    out[name] = inner;
}

const php = Object.entries(out)
    .map(([key, value]) => `    '${key}' => '${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`)
    .join('\n');

fs.writeFileSync(
    'resources/icons.php',
    `<?php\n\n/* Generated by build-icons.js — Lucide icon paths (ISC licence). */\n\nreturn [\n${php}\n];\n`,
);

console.log(`Wrote ${Object.keys(out).length} icons. Missing: ${missing.join(', ') || 'none'}`);
